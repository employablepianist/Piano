// Site graph — D3.js force simulation
// Nodes from sitemap.xml, edges from backlinks.json

// Base path this site is actually served under (e.g. "/Piano/" on GitHub
// Pages, "/" at a domain root or local dev) — read from a value the graph.html
// template bakes in via config.base_url, since a plain static .js file has no
// way to know its own deployment path otherwise.
let dataBase = new URL(window.__BASE_URL__).pathname;
if (!dataBase.endsWith('/')) dataBase += '/';

Promise.all([
  fetch(dataBase + 'sitemap.xml').then(r => r.text()),
  fetch(dataBase + 'backlinks.json').then(r => r.json())
]).then(([sitemapXml, backlinks]) => {
  // Parse sitemap: extract URLs and titles from <loc> tags
  const parser = new DOMParser();
  const xml = parser.parseFromString(sitemapXml, 'text/xml');

  // sitemap.xml and backlinks.json are generated by separate build steps and
  // may be baked with different base-path prefixes (e.g. a dev server serving
  // at "/" vs. GitHub Pages serving under "/Piano/"). Rather than assume both
  // sides agree on one literal prefix, canonicalize each path down to its
  // "/p/..." or "/w/..." content-section suffix for matching purposes only —
  // the original (prefixed) path is kept as each node's id/href.
  const canonical = u => {
    const m = u.match(/\/(?:p|w)\/.*$/);
    return m ? m[0] : u;
  };

  const urls = [...xml.querySelectorAll('loc')]
    .map(loc => loc.textContent.replace(/^https?:\/\/[^\/]+/, ''))
    .filter(u => {
      const c = canonical(u);
      return (c.startsWith('/p/') || c.startsWith('/w/')) && !c.match(/^\/[pw]\/$/);
    });

  // Build nodes from sitemap URLs (title = filename from path)
  const nodes = urls.map(url => {
    const parts = url.replace(/\/$/, '').split('/');
    const last = parts[parts.length - 1];
    // Pretty title: replace hyphens with spaces, capitalize
    const title = last.charAt(0).toUpperCase() + last.slice(1).replace(/-/g, ' ');
    return {
      id: url,
      title: title,
      section: canonical(url).startsWith('/p/') ? 'blog' : 'wiki'
    };
  });

  // Map canonical section-path -> actual node id, so backlinks (which may use
  // a different prefix than sitemap.xml) can still be resolved to real nodes.
  const canonicalToId = new Map(nodes.map(n => [canonical(n.id), n.id]));

  // Build edge list from backlinks (only between sitemap pages)
  const links = [];
  for (const [target, sources] of Object.entries(backlinks)) {
    const targetId = canonicalToId.get(canonical(target));
    if (!targetId) continue;
    for (const src of sources) {
      const srcPath = typeof src === 'string' ? src : src.path;
      const srcId = canonicalToId.get(canonical(srcPath));
      if (srcId) {
        links.push({ source: targetId, target: srcId });
      }
    }
  }

  // Count backlinks per node
  const backlinkCount = {};
  links.forEach(l => {
    backlinkCount[l.target] = (backlinkCount[l.target] || 0) + 1;
  });

  // Update titles from backlinks
  let titleUpdates = 0;
  for (const [target, sources] of Object.entries(backlinks)) {
    for (const src of sources) {
      const srcData = typeof src === 'string' ? { path: src, title: src } : src;
      const nodeId = canonicalToId.get(canonical(srcData.path));
      const node = nodeId && nodes.find(n => n.id === nodeId);
      if (node && srcData.title && !srcData.title.startsWith('/')) {
        node.title = srcData.title;
        titleUpdates++;
      }
    }
  }

  const data = { nodes, links };

  // ── D3 rendering ──
  const width = document.getElementById('graph').clientWidth;
  const height = Math.max(600, window.innerHeight * 0.7);

  const svg = d3.select('#graph')
    .append('svg')
    .attr('viewBox', [0, 0, width, height]);

  const link = svg.append('g')
    .attr('stroke', '#d4d4d4')
    .attr('stroke-opacity', 0.4)
    .selectAll('line')
    .data(links)
    .join('line')
    .attr('stroke-width', 0.5);

  const node = svg.append('g')
    .selectAll('a')
    .data(nodes)
    .join('a')
    .attr('href', d => d.id)
    .attr('class', 'node')
    .append('text')
    .text(d => d.title)
    .attr('text-anchor', 'middle')
    .attr('font-size', d => 11 + (backlinkCount[d.id] || 0) * 0.8)
    .attr('fill', d => d.section === 'blog' ? '#3b82f6' : '#555')
    .attr('cursor', 'pointer')
    .on('mouseenter', function(_, d) {
      d3.select(this).attr('font-weight', 'bold').attr('fill', '#3b82f6');
      link.attr('stroke', l => (l.source.id === d.id || l.target.id === d.id) ? '#3b82f6' : '#d4d4d4')
          .attr('stroke-opacity', l => (l.source.id === d.id || l.target.id === d.id) ? 0.8 : 0.4)
          .attr('stroke-width', l => (l.source.id === d.id || l.target.id === d.id) ? 1.5 : 0.5);
      node.attr('opacity', n => (n.id === d.id || links.some(l => (l.source.id === d.id && l.target.id === n.id) || (l.target.id === d.id && l.source.id === n.id))) ? 1 : 0.2);
    })
    .on('mouseleave', function(_, d) {
      d3.select(this).attr('font-weight', null).attr('fill', d.section === 'blog' ? '#3b82f6' : '#555');
      link.attr('stroke', '#d4d4d4').attr('stroke-opacity', 0.4).attr('stroke-width', 0.5);
      node.attr('opacity', 1);
    });

  const sim = d3.forceSimulation(nodes)
    .force('link', d3.forceLink(links).id(d => d.id).distance(60).strength(0.4))
    .force('charge', d3.forceManyBody().strength(-20))
    .force('center', d3.forceCenter(width / 2, height / 2))
    .force('collision', d3.forceCollide().radius(d => Math.max(25, (d.title?.length || 5) * 3)))
    .on('tick', () => {
      link
        .attr('x1', d => d.source.x)
        .attr('y1', d => d.source.y)
        .attr('x2', d => d.target.x)
        .attr('y2', d => d.target.y);
      node
        .attr('x', d => d.x)
        .attr('y', d => d.y);
    });

  svg.call(d3.zoom()
    .extent([[0, 0], [width, height]])
    .scaleExtent([0.3, 5])
    .on('zoom', ({transform}) => {
      svg.selectAll('g').attr('transform', transform);
    }));
});
